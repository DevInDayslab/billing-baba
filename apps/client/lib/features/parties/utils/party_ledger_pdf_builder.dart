import 'dart:typed_data';

import 'package:billing_baba/features/parties/models/party_ledger_model.dart';
import 'package:billing_baba/features/parties/models/party_model.dart';
import 'package:billing_baba/features/print/models/pdf_page_profile.dart';
import 'package:billing_baba/features/print/templates/invoice/invoice_pdf_fonts.dart';
import 'package:billing_baba/features/print/templates/invoice/invoice_pdf_theme.dart';
import 'package:billing_baba/features/print/templates/invoice/invoice_pdf_widgets.dart';
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

/// Builds A4 PDF bytes for a party ledger statement.
abstract final class PartyLedgerPdfBuilder {
  static const _headers = [
    'Date',
    'Type',
    'Ref #',
    'Total',
    'Balance',
    'Status',
  ];

  static final _dateFormat = DateFormat('dd/MM/yyyy');
  static final _generatedDateFormat = DateFormat('dd MMM yyyy, hh:mm a');

  static Future<Uint8List> build({
    required PartyModel party,
    required List<PartyLedgerTransactionModel> transactions,
    String? businessName,
    double? outstanding,
    double? creditLimit,
  }) async {
    await InvoicePdfFonts.ensureLoaded();

    final resolvedOutstanding = outstanding ?? party.balance;
    final resolvedCreditLimit = creditLimit ??
        (party.hasCustomCreditLimit
            ? double.tryParse(party.creditLimit.replaceAll(',', ''))
            : null);

    final rows = transactions.map(_transactionRow).toList();
    final generatedAt = _generatedDateFormat.format(DateTime.now());

    final pdf = pw.Document();
    pdf.addPage(
      pw.MultiPage(
        pageTheme: pw.PageTheme(
          pageFormat: PdfPageProfile.transactionCompact.pageFormat,
          margin: PdfPageProfile.transactionCompact.pageMargins,
        ),
        header: (context) {
          if (context.pageNumber != 1) return pw.SizedBox();
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.stretch,
            children: [
              pw.Text(
                party.name,
                style: InvoicePdfTheme.title(),
              ),
              pw.SizedBox(height: InvoicePdfTheme.spacingSm),
              pw.Row(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Expanded(child: _leftMetadataColumn(party)),
                  pw.SizedBox(width: InvoicePdfTheme.spacingLg),
                  pw.Expanded(
                    child: _rightMetadataColumn(
                      party: party,
                      businessName: businessName,
                      outstanding: resolvedOutstanding,
                      creditLimit: resolvedCreditLimit,
                    ),
                  ),
                ],
              ),
              pw.SizedBox(height: InvoicePdfTheme.spacingMd),
              pw.Divider(color: InvoicePdfTheme.border, thickness: 0.5),
              pw.SizedBox(height: InvoicePdfTheme.spacingMd),
              pw.Text(
                'Transactions',
                style: InvoicePdfTheme.heading(size: 11),
              ),
              pw.SizedBox(height: InvoicePdfTheme.spacingSm),
            ],
          );
        },
        footer: (context) => pw.Column(
          children: [
            pw.Align(
              child: pw.Text(
                'Generated by Billing Baba | $generatedAt',
                style: InvoicePdfTheme.mutedBody(size: 8),
              ),
            ),
            pw.SizedBox(height: InvoicePdfTheme.spacingXs),
            pw.Align(
              alignment: pw.Alignment.centerRight,
              child: pw.Text(
                'Page ${context.pageNumber} of ${context.pagesCount}',
                style: InvoicePdfTheme.mutedBody(size: 8),
              ),
            ),
          ],
        ),
        build: (context) => [
          if (rows.isEmpty)
            pw.Text(
              'No transactions yet',
              style: InvoicePdfTheme.mutedBody(),
            )
          else
            pw.Table(
              border: const pw.TableBorder(
                left: pw.BorderSide(color: InvoicePdfTheme.border, width: 0.5),
                right: pw.BorderSide(color: InvoicePdfTheme.border, width: 0.5),
                top: pw.BorderSide(color: InvoicePdfTheme.border, width: 0.5),
                bottom: pw.BorderSide(
                  color: InvoicePdfTheme.border,
                  width: 0.5,
                ),
                horizontalInside: pw.BorderSide(
                  color: InvoicePdfTheme.border,
                  width: 0.5,
                ),
                verticalInside: pw.BorderSide(
                  color: InvoicePdfTheme.border,
                  width: 0.5,
                ),
              ),
              columnWidths: {
                0: const pw.IntrinsicColumnWidth(),
                1: const pw.FlexColumnWidth(1.4),
                2: const pw.FlexColumnWidth(1.2),
                3: const pw.IntrinsicColumnWidth(),
                4: const pw.IntrinsicColumnWidth(),
                5: const pw.IntrinsicColumnWidth(),
              },
              children: [
                pw.TableRow(
                  decoration: const pw.BoxDecoration(
                    color: InvoicePdfTheme.headerFill,
                  ),
                  children: [
                    for (final header in _headers)
                      InvoicePdfWidgets.tableHeaderCell(
                        header,
                        align: _columnAlign(header),
                      ),
                  ],
                ),
                for (var i = 0; i < rows.length; i++)
                  pw.TableRow(
                    decoration: pw.BoxDecoration(
                      color: i.isEven ? PdfColors.white : PdfColors.grey100,
                    ),
                    children: [
                      for (var j = 0; j < _headers.length; j++)
                        InvoicePdfWidgets.tableBodyCell(
                          j < rows[i].length ? rows[i][j] : '',
                          align: _columnAlign(_headers[j]),
                        ),
                    ],
                  ),
              ],
            ),
        ],
      ),
    );

    return pdf.save();
  }

  static pw.Widget _leftMetadataColumn(PartyModel party) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.stretch,
      children: [
        _metaLine('Phone', PartyModel.displayOrDash(party.phone)),
        _metaLine('GSTIN', PartyModel.displayOrDash(party.gstin)),
        _metaLine('Address', PartyModel.displayOrDash(_billingAddress(party))),
      ],
    );
  }

  static pw.Widget _rightMetadataColumn({
    required PartyModel party,
    required String? businessName,
    required double outstanding,
    required double? creditLimit,
  }) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.stretch,
      children: [
        _metaLine('Party Type', party.partyTypeLabel),
        _metaLine(
          'Business Name',
          PartyModel.displayOrDash(businessName),
        ),
        _metaLine(
          'Credit Limit',
          creditLimit != null
              ? PartyModel.formatCurrency(creditLimit)
              : PartyModel.displayCreditLimit(
                  hasCustomCreditLimit: party.hasCustomCreditLimit,
                  creditLimit: party.creditLimit,
                ),
        ),
        _metaLine(
          'Outstanding',
          PartyModel.displayOutstanding(outstanding),
        ),
      ],
    );
  }

  static pw.Widget _metaLine(String label, String value) {
    return pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 4),
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.SizedBox(
            width: 78,
            child: pw.Text(
              label,
              style: InvoicePdfTheme.mutedBody(size: 8.5),
            ),
          ),
          pw.Expanded(
            child: pw.Text(
              value,
              style: InvoicePdfTheme.body(),
              textAlign: pw.TextAlign.right,
            ),
          ),
        ],
      ),
    );
  }

  static String _billingAddress(PartyModel party) {
    final primary = party.billingAddress.trim();
    if (primary.isNotEmpty) return primary;

    final parts = [
      party.addressLine,
      party.city,
      party.state,
      party.pincode,
    ].where((part) => part.trim().isNotEmpty);

    return parts.join(', ');
  }

  static List<String> _transactionRow(PartyLedgerTransactionModel transaction) {
    final total = _transactionTotal(transaction);
    return [
      _dateFormat.format(transaction.date),
      transaction.type,
      PartyModel.displayOrDash(transaction.referenceNumber),
      PartyModel.formatCurrency(total),
      PartyModel.formatCurrency(transaction.balanceAfter),
      _transactionStatus(transaction),
    ];
  }

  static double _transactionTotal(PartyLedgerTransactionModel transaction) =>
      transaction.debit > 0 ? transaction.debit : transaction.credit;

  static String _transactionStatus(PartyLedgerTransactionModel transaction) {
    return switch (transaction.entryType) {
      'payment' => 'Paid',
      'sale' || 'purchase' => 'Paid',
      'return' => 'Returned',
      _ => '—',
    };
  }

  static pw.TextAlign _columnAlign(String header) {
    final normalized = header.toLowerCase();
    if (normalized.contains('total') ||
        normalized.contains('balance') ||
        normalized.contains('amount')) {
      return pw.TextAlign.right;
    }
    return pw.TextAlign.left;
  }
}
